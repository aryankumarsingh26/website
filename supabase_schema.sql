-- 1. Users Table (The 3 Friends)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    avatar TEXT NOT NULL DEFAULT '👤',
    color TEXT NOT NULL DEFAULT '#f59e0b',
    pin TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Categories Table
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    icon TEXT NOT NULL,
    badge_color TEXT NOT NULL
);

-- 3. Inventory Items Table
CREATE TABLE IF NOT EXISTS public.items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 0,
    unit TEXT NOT NULL DEFAULT 'packet',
    low_stock_threshold INTEGER NOT NULL DEFAULT 2,
    is_maggi INTEGER DEFAULT 0,
    notes TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Activity Log Table
CREATE TABLE IF NOT EXISTS public.activity_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    user_name TEXT NOT NULL,
    action_type TEXT NOT NULL, -- 'consume', 'restock', 'add', 'edit', 'delete', 'expense'
    item_name TEXT NOT NULL,
    quantity_change INTEGER NOT NULL DEFAULT 0,
    cost NUMERIC(10, 2) DEFAULT 0.0,
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Expenses Table (Hisab-Kitab)
CREATE TABLE IF NOT EXISTS public.expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_id BIGINT NOT NULL,
    payer_name TEXT NOT NULL,
    title TEXT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    split_count INTEGER NOT NULL DEFAULT 3,
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Shopping List Table (Bazaar Wishlist)
CREATE TABLE IF NOT EXISTS public.shopping_list (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name TEXT NOT NULL,
    category TEXT DEFAULT 'General',
    quantity INTEGER DEFAULT 1,
    unit TEXT DEFAULT 'packet',
    added_by TEXT NOT NULL,
    status TEXT DEFAULT 'pending', -- 'pending', 'bought'
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activity_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.shopping_list ENABLE ROW LEVEL SECURITY;

-- Allow Public/Anon Access for the 3 Roommates
CREATE POLICY "Public Read/Write for Users" ON public.users FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public Read/Write for Categories" ON public.categories FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public Read/Write for Items" ON public.items FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public Read/Write for Activity Log" ON public.activity_log FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public Read/Write for Expenses" ON public.expenses FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public Read/Write for Shopping List" ON public.shopping_list FOR ALL USING (true) WITH CHECK (true);

